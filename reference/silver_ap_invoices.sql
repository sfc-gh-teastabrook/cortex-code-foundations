-- Silver AP invoices: SAP + Oracle + Baan + Workday (business rules BR-001..BR-010)
USE DATABASE COCO_WORKSHOP;
USE SCHEMA PIPELINE_LAB;
USE WAREHOUSE COCO_WORKSHOP_WH;

CREATE OR REPLACE DYNAMIC TABLE SILVER_AP_INVOICES
  TARGET_LAG = '1 hour'           -- BR-009
  WAREHOUSE = COCO_WORKSHOP_WH
AS
WITH unioned AS (
    SELECT 'SAP' AS SOURCE_SYSTEM, INVOICE_ID, INVOICE_NUMBER, VENDOR_ID, VENDOR_NAME,
           INVOICE_DATE, DUE_DATE, INVOICE_AMOUNT, CURRENCY_CODE, PAYMENT_TERMS, PO_NUMBER,
           LINE_DESCRIPTION, GL_ACCOUNT, COST_CENTER, APPROVAL_STATUS, CREATED_AT
    FROM COCO_WORKSHOP.SOURCE_DATA.BRONZE_SAP_AP_INVOICES
    UNION ALL
    SELECT 'ORACLE', INV_ID, INV_NUM, SUPPLIER_ID, SUPPLIER_NAME, INV_DATE, PAYMENT_DUE_DATE,
           TOTAL_AMOUNT, CURRENCY, TERMS_CODE, PURCHASE_ORDER, DESCRIPTION, ACCOUNT_CODE,
           DEPT_CODE, CASE STATUS WHEN 'VALIDATED' THEN 'APPROVED' ELSE STATUS END, CREATION_DATE
    FROM COCO_WORKSHOP.SOURCE_DATA.BRONZE_ORACLE_AP_INVOICES
    UNION ALL
    SELECT 'BAAN', BAN_INVOICE_ID, BAN_INVOICE_REF, BAN_VENDOR_CODE, BAN_VENDOR_DESC, BAN_INV_DATE,
           BAN_PAY_DATE, BAN_AMOUNT, BAN_CURR, BAN_PAY_TERMS, BAN_PO_REF, BAN_LINE_DESC, BAN_GL_CODE,
           BAN_COST_CTR, CASE BAN_STATUS WHEN 'POSTED' THEN 'APPROVED' ELSE BAN_STATUS END, BAN_CREATED
    FROM COCO_WORKSHOP.SOURCE_DATA.BRONZE_BAAN_AP_INVOICES
    QUALIFY ROW_NUMBER() OVER (PARTITION BY BAN_INVOICE_REF ORDER BY BAN_CREATED DESC) = 1   -- BR-003
    UNION ALL
    SELECT 'WORKDAY', WD_INVOICE_ID, WD_INVOICE_NUM, WD_SUPPLIER_ID, WD_SUPPLIER_NAME, WD_INVOICE_DATE,
           WD_DUE_DATE, WD_AMOUNT, WD_CURRENCY, WD_PAY_TERMS, WD_PO_NUMBER, WD_MEMO, WD_LEDGER_ACCOUNT,
           WD_COST_CENTER,
           CASE WD_APPROVAL_STATUS WHEN 'Approved' THEN 'APPROVED' WHEN 'In Review' THEN 'PENDING'
                ELSE UPPER(WD_APPROVAL_STATUS) END,
           WD_CREATED_DATE
    FROM COCO_WORKSHOP.SOURCE_DATA.BRONZE_WORKDAY_AP_INVOICES
)
SELECT * FROM unioned;

-- Proof query
SELECT SOURCE_SYSTEM, APPROVAL_STATUS, COUNT(*) AS RECORD_COUNT
FROM COCO_WORKSHOP.PIPELINE_LAB.SILVER_AP_INVOICES
GROUP BY ALL ORDER BY 1, 2;
